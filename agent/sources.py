"""
sources.py — One shared list of every web source the research team has seen.

Why this exists: the critic can only fact-check a claim if it knows exactly
which source the claim came from. So every search result gets a short id
("S1", "S2", ...) the moment it's found, researchers cite claims with those
ids ("LangGraph models agents as graphs [S3]"), and the critic looks the ids
back up here.

This is SHARED STATE written by several researchers at once, which is the
classic multi-agent hazard. Two design choices keep it safe:

  1. A lock. Searches run in background threads (asyncio.to_thread), so two
     researchers really can call add() at the same moment. Without the lock,
     both could read len()==4 and both create "S5" for different pages.
  2. Idempotent ids. The same URL always maps to the same id, so if two
     researchers (or a retry) find the same page, it's stored once and both
     citations point to the same entry instead of conflicting.
"""

import re
import threading
from dataclasses import dataclass

# Search snippets are capped so prompts stay small (Groq's free tier limits
# tokens per minute, and the critic reads every cited snippet).
MAX_SNIPPET_CHARS = 300

@dataclass(frozen=True)
class Source:
    id: str
    title: str
    url: str
    snippet: str

    def render(self) -> str:
        """
        How a source is shown to the LLM: id first, so it's easy to cite.
        """
        return f"[{self.id}] {self.title}\n{self.snippet}\n{self.url}"

class SourceRegistry:
    def __init__(self) -> None:
        self._by_id: dict[str, Source] = {}
        self._id_by_url: dict[str, str] = {}
        self._lock = threading.Lock()

    def add(self, title: str, url: str, snippet: str) -> Source:
        """
        Register a source and return it. Same URL -> same Source.
        """
        key = url.strip().rstrip("/").lower()
        with self._lock:  # read-check-write must happen as one step
            if key in self._id_by_url:
                return self._by_id[self._id_by_url[key]]
            source = Source(id=f"S{len(self._by_id) + 1}", title=title.strip(),
                            url=url.strip(), snippet=snippet.strip()[:MAX_SNIPPET_CHARS])
            self._by_id[source.id] = source
            self._id_by_url[key] = source.id
            return source

    def get(self, source_id: str) -> Source | None:
        return self._by_id.get(source_id)

    def __len__(self) -> int:
        return len(self._by_id)

# Matches the inside of any [...] group, e.g. "[S1]", "[S2, S5]" or "[S3; S4]".
_BRACKETS = re.compile(r"\[([^\[\]]+)\]")
_ID = re.compile(r"\bS\d+\b")

def cited_ids(text: str) -> list[str]:
    """
    Every source id cited in `text`, in order of first appearance, no repeats.
    Only bracketed ids count, so a sentence like "S3 storage" isn't a citation.
    """
    seen: dict[str, None] = {}  # a dict keeps insertion order, unlike a set
    for group in _BRACKETS.findall(text):
        for source_id in _ID.findall(group):
            seen.setdefault(source_id, None)
    return list(seen)

def render_sources_section(text: str, registry: SourceRegistry) -> str:
    """
    Build the report's "Sources" list from the ids actually cited in `text`.
    The list is generated by code, not written by the LLM, so it can never
    contain a made-up URL.
    """
    lines = []
    for source_id in cited_ids(text):
        source = registry.get(source_id)
        if source:
            lines.append(f"- **[{source.id}]** [{source.title or source.url}]({source.url})")
    return "## Sources\n\n" + "\n".join(lines) if lines else ""
